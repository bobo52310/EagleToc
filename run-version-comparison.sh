#!/bin/bash

# Smart TOC 版本比較測試腳本
# 使用方法: ./run-version-comparison.sh [1|2|3|all]

set -e

# 顏色定義
RED='\033[0;31m'
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# 版本信息
declare -A VERSIONS=(
    ["1"]="v1-basic-scroll|基本滾動同步|傳統事件監聽器"
    ["2"]="v2-enhanced-scroll|增強滾動同步|防抖+視覺反饋"
    ["3"]="v3-smart-scroll|智能滾動同步|Intersection Observer+AI"
)

print_header() {
    echo -e "${BLUE}================================${NC}"
    echo -e "${BLUE}   Smart TOC 版本比較工具${NC}"
    echo -e "${BLUE}================================${NC}"
    echo ""
}

print_version_info() {
    local version=$1
    IFS='|' read -ra INFO <<< "${VERSIONS[$version]}"
    echo -e "${GREEN}版本 $version: ${INFO[1]}${NC}"
    echo -e "  🔧 實現方式: ${INFO[2]}"
    echo -e "  📁 工作目錄: ../smart-toc-${INFO[0]}"
    echo -e "  🌿 Git 分支: scroll-sync-v$version"
    echo ""
}

check_worktree() {
    local version=$1
    IFS='|' read -ra INFO <<< "${VERSIONS[$version]}"
    local worktree_path="../smart-toc-${INFO[0]}"
    
    if [ ! -d "$worktree_path" ]; then
        echo -e "${RED}❌ 錯誤: 找不到工作目錄 $worktree_path${NC}"
        echo -e "${YELLOW}請先運行以下命令創建 worktree:${NC}"
        echo "  git worktree add $worktree_path scroll-sync-v$version"
        return 1
    fi
    return 0
}

open_version() {
    local version=$1
    
    echo -e "${BLUE}🚀 啟動版本 $version 測試...${NC}"
    print_version_info $version
    
    if ! check_worktree $version; then
        return 1
    fi
    
    IFS='|' read -ra INFO <<< "${VERSIONS[$version]}"
    local worktree_path="../smart-toc-${INFO[0]}"
    
    # 檢查是否有 web 服務器運行
    if command -v python3 &> /dev/null; then
        echo -e "${YELLOW}📡 啟動 HTTP 服務器...${NC}"
        cd "$worktree_path"
        echo -e "  📂 服務目錄: $(pwd)"
        echo -e "  🌐 訪問地址: http://localhost:800$version"
        echo -e "  📄 測試頁面: http://localhost:800$version/scroll-sync-test.html"
        echo -e "  📊 比較頁面: http://localhost:800$version/scroll-sync-comparison.html"
        echo ""
        echo -e "${GREEN}🎯 準備就緒！請在瀏覽器中測試版本 $version${NC}"
        echo -e "${YELLOW}按 Ctrl+C 停止服務器${NC}"
        echo ""
        
        # 啟動服務器，每個版本使用不同端口
        python3 -m http.server "800$version"
    else
        echo -e "${YELLOW}⚠️  未找到 Python3，請手動開啟文件:${NC}"
        echo -e "  file://$worktree_path/scroll-sync-test.html"
    fi
}

run_all_versions() {
    echo -e "${BLUE}🎯 並行啟動所有版本進行比較...${NC}"
    echo ""
    
    for version in 1 2 3; do
        if ! check_worktree $version; then
            continue
        fi
        
        IFS='|' read -ra INFO <<< "${VERSIONS[$version]}"
        local worktree_path="../smart-toc-${INFO[0]}"
        
        echo -e "${GREEN}啟動版本 $version 服務器 (端口 800$version)...${NC}"
        
        # 在背景啟動服務器
        (cd "$worktree_path" && python3 -m http.server "800$version" > /dev/null 2>&1) &
        local pid=$!
        echo "  PID: $pid"
    done
    
    echo ""
    echo -e "${GREEN}✅ 所有版本已啟動！${NC}"
    echo ""
    echo -e "${YELLOW}📱 測試地址:${NC}"
    echo "  版本 1: http://localhost:8001/scroll-sync-test.html"
    echo "  版本 2: http://localhost:8002/scroll-sync-test.html"
    echo "  版本 3: http://localhost:8003/scroll-sync-test.html"
    echo ""
    echo -e "${YELLOW}📊 比較頁面:${NC}"
    echo "  http://localhost:8001/scroll-sync-comparison.html"
    echo ""
    echo -e "${BLUE}💡 建議：${NC}"
    echo "  1. 在三個不同的瀏覽器窗口中開啟三個版本"
    echo "  2. 同時滾動頁面，觀察 TOC 同步行為的差異"
    echo "  3. 注意視覺效果、響應速度、準確性的差別"
    echo ""
    echo -e "${RED}按任意鍵停止所有服務器...${NC}"
    read -n 1
    
    # 停止所有 Python 服務器
    pkill -f "python3 -m http.server 800"
    echo -e "${GREEN}所有服務器已停止${NC}"
}

generate_comparison_report() {
    echo -e "${BLUE}📋 生成版本對比報告...${NC}"
    
    local report_file="version-comparison-report.md"
    
    cat > "$report_file" << EOF
# Smart TOC 滾動同步版本對比報告

生成時間: $(date)

## 版本概述

| 版本 | 名稱 | 實現方式 | 分支 |
|------|------|----------|------|
EOF
    
    for version in 1 2 3; do
        IFS='|' read -ra INFO <<< "${VERSIONS[$version]}"
        echo "| $version | ${INFO[1]} | ${INFO[2]} | scroll-sync-v$version |" >> "$report_file"
    done
    
    cat >> "$report_file" << EOF

## Git Worktree 結構

\`\`\`
$(git worktree list)
\`\`\`

## 提交歷史

### 版本 1 (基本實現)
\`\`\`
$(cd ../smart-toc-v1-basic-scroll 2>/dev/null && git log --oneline -3 || echo "工作目錄不存在")
\`\`\`

### 版本 2 (增強實現)
\`\`\`
$(cd ../smart-toc-v2-enhanced-scroll 2>/dev/null && git log --oneline -3 || echo "工作目錄不存在")
\`\`\`

### 版本 3 (智能實現)
\`\`\`
$(cd ../smart-toc-v3-smart-scroll 2>/dev/null && git log --oneline -3 || echo "工作目錄不存在")
\`\`\`

## 測試指南

1. **單版本測試**: \`./run-version-comparison.sh [1|2|3]\`
2. **並行對比**: \`./run-version-comparison.sh all\`
3. **測試頁面**: 各版本的 \`scroll-sync-test.html\`
4. **比較說明**: \`scroll-sync-comparison.html\`

## 截圖建議

為每個版本拍攝以下場景：
- 初始載入狀態
- 滾動過程中的視覺反饋
- 不同標題的高亮效果
- 版本特有的功能展示

## 性能測試

建議使用瀏覽器開發者工具的 Performance 面板：
1. 開始錄製 performance
2. 進行長時間滾動操作
3. 分析 CPU 使用率和事件頻率
4. 比較三個版本的性能差異

---
Generated by Smart TOC Version Comparison Tool
EOF
    
    echo -e "${GREEN}✅ 報告已生成: $report_file${NC}"
}

show_help() {
    print_header
    echo -e "${YELLOW}使用方法:${NC}"
    echo "  $0 [選項]"
    echo ""
    echo -e "${YELLOW}選項:${NC}"
    echo "  1          啟動版本 1 (基本滾動同步)"
    echo "  2          啟動版本 2 (增強滾動同步)" 
    echo "  3          啟動版本 3 (智能滾動同步)"
    echo "  all        並行啟動所有版本進行對比"
    echo "  report     生成版本對比報告"
    echo "  help       顯示此幫助信息"
    echo ""
    echo -e "${YELLOW}範例:${NC}"
    echo "  $0 1       # 測試基本版本"
    echo "  $0 all     # 同時測試所有版本"
    echo "  $0 report  # 生成對比報告"
    echo ""
    echo -e "${BLUE}版本信息:${NC}"
    for version in 1 2 3; do
        print_version_info $version
    done
}

# 主程序
main() {
    case "${1:-help}" in
        1|2|3)
            print_header
            open_version $1
            ;;
        all)
            print_header
            run_all_versions
            ;;
        report)
            print_header
            generate_comparison_report
            ;;
        help|--help|-h)
            show_help
            ;;
        *)
            echo -e "${RED}❌ 錯誤: 未知選項 '$1'${NC}"
            echo ""
            show_help
            exit 1
            ;;
    esac
}

# 檢查必要的依賴
if ! command -v git &> /dev/null; then
    echo -e "${RED}❌ 錯誤: 未找到 git 命令${NC}"
    exit 1
fi

# 確保在正確的目錄中
if [ ! -f "manifest.json" ]; then
    echo -e "${RED}❌ 錯誤: 請在 Smart TOC 專案根目錄中運行此腳本${NC}"
    exit 1
fi

main "$@"